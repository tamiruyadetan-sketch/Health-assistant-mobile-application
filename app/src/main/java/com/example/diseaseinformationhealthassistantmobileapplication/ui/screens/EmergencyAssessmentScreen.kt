// -------------------------------------------------------------------- steps

@Composable
private fun AgeStep(answers: AssessmentAnswers, language: String, onChange: (AssessmentAnswers) -> Unit) {
    OutlinedTextField(
        value = answers.age,
        onValueChange = { input ->
            if (input.length <= 3 && input.all { it.isDigit() }) {
                onChange(answers.copy(age = input))
            }
        },
        label = { Text(loc(language, "Your age (years)", "Umrii keessii (waggaa)", "ዕድሜዎ (ዓመት)")) },
        keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Number),
        singleLine = true,
        modifier = Modifier.fillMaxWidth()
    )
    Spacer(modifier = Modifier.height(8.dp))
    Text(
        text = loc(
            language,
            "Enter a number, for example 34.",
            "Lakkoofsa galchaa, fakkaataan 34.",
            "ቁጥር ያስገቡ፣ ለምሳሌ 34።"
        ),
        style = MaterialTheme.typography.bodySmall,
        color = MaterialTheme.colorScheme.secondary
    )
}

@Composable
private fun SingleChoiceStep(
    options: List<ChoiceOption>,
    selected: String?,
    language: String,
    onSelect: (String) -> Unit
) {
    Column {
        options.forEach { option ->
            Row(
                modifier = Modifier
                    .fillMaxWidth()
                    .clickable { onSelect(option.id) }
                    .padding(vertical = 2.dp),
                verticalAlignment = Alignment.CenterVertically
            ) {
                RadioButton(
                    selected = selected == option.id,
                    onClick = { onSelect(option.id) }
                )
                Text(
                    text = option.label(language),
                    style = MaterialTheme.typography.bodyLarge
                )
            }
        }
    }
}

@Composable
private fun MultiChoiceStep(
    options: List<ChoiceOption>,
    selected: Set<String>,
    language: String,
    onToggle: (String) -> Unit
) {
    Column {
        options.forEach { option ->
            Row(
                modifier = Modifier
                    .fillMaxWidth()
                    .clickable { onToggle(option.id) }
                    .padding(vertical = 2.dp),
                verticalAlignment = Alignment.CenterVertically
            ) {
                Checkbox(
                    checked = option.id in selected,
                    onCheckedChange = { onToggle(option.id) }
                )
                Text(
                    text = option.label(language),
                    style = MaterialTheme.typography.bodyLarge
                )
            }
        }
    }
}

@Composable
private fun SymptomsStep(
    answers: AssessmentAnswers,
    language: String,
    onChange: (AssessmentAnswers) -> Unit,
    onSpeak: () -> Unit
) {
    Text(
        text = voiceTip(language),
        style = MaterialTheme.typography.bodySmall,
        color = MaterialTheme.colorScheme.secondary
    )
    Spacer(modifier = Modifier.height(8.dp))
    MultiChoiceStep(
        options = AssessmentOptions.symptoms,
        selected = answers.symptoms,
        language = language,
        onToggle = { id ->
            val current = answers.symptoms
            onChange(answers.copy(symptoms = if (id in current) current - id else current + id))
        }
    )
    if ("other" in answers.symptoms) {
        Spacer(modifier = Modifier.height(8.dp))
        OutlinedTextField(
            value = answers.otherSymptoms,
            onValueChange = { onChange(answers.copy(otherSymptoms = it)) },
            label = {
                Text(
                    loc(
                        language,
                        "Describe your other symptoms",
                        "Dhukkubbii biraa ibsi",
                        "ሌሎች ስምምነቶችዎን ይግለጹ"
                    )
                )
            },
            modifier = Modifier.fillMaxWidth(),
            trailingIcon = {
                IconButton(onClick = onSpeak) {
                    Icon(
                        Icons.Default.Mic,
                        contentDescription = loc(language, "Speak", "Afaanii dhageessi", "ንግግር")
                    )
                }
            }
        )
    }
}

@Composable
private fun ConditionsStep(
    answers: AssessmentAnswers,
    language: String,
    onChange: (AssessmentAnswers) -> Unit
) {
    MultiChoiceStep(
        options = AssessmentOptions.conditions,
        selected = answers.conditions,
        language = language,
        onToggle = { id ->
            val current = answers.conditions
            val next = when {
                // "None" is exclusive with every other condition.
                id == "none" -> if ("none" in current) emptySet() else setOf("none")
                id in current -> current - id
                else -> (if ("none" in current) current - "none" else current) + id
            }
            onChange(answers.copy(conditions = next))
        }
    )
    if ("other" in answers.conditions) {
        Spacer(modifier = Modifier.height(8.dp))
        OutlinedTextField(
            value = answers.otherCondition,
            onValueChange = { onChange(answers.copy(otherCondition = it)) },
            label = {
                Text(
                    loc(language, "Which condition?", "Dhukkubii kam?", "የትኛው በሽታ?")
                )
            },
            singleLine = true,
            modifier = Modifier.fillMaxWidth()
        )
    }
}

@Composable
private fun MedicationsStep(
    answers: AssessmentAnswers,
    language: String,
    onChange: (AssessmentAnswers) -> Unit,
    onSpeak: () -> Unit
) {
    SingleChoiceStep(
        options = yesNoOptions(language),
        selected = answers.onMedications,
        language = language,
        onSelect = { id -> onChange(answers.copy(onMedications = id)) }
    )
    if (answers.onMedications == "yes") {
        Spacer(modifier = Modifier.height(8.dp))
        OutlinedTextField(
            value = answers.medicationsText,
            onValueChange = { onChange(answers.copy(medicationsText = it)) },
            label = {
                Text(
                    loc(
                        language,
                        "Which medications? (optional)",
                        "Dawaa kam? (filatamaa)",
                        "የትኛው መድኃኒት? (አማራጭ)"
                    )
                )
            },
            modifier = Modifier.fillMaxWidth(),
            trailingIcon = {
                IconButton(onClick = onSpeak) {
                    Icon(
                        Icons.Default.Mic,
                        contentDescription = loc(language, "Speak", "Afaanii dhageessi", "ንግግር")
                    )
                }
            }
        )
        Spacer(modifier = Modifier.height(4.dp))
        Text(
            text = voiceTip(language),
            style = MaterialTheme.typography.bodySmall,
            color = MaterialTheme.colorScheme.secondary
        )
    }
}

@Composable
