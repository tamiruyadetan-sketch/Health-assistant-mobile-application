private const val TOTAL_STEPS = 9 // age, gender, symptoms, duration, severity, conditions, medications, allergies, previous

private fun loc(language: String, en: String, om: String, am: String): String = when (language) {
    "om" -> om
    "am" -> am
    else -> en
}

/**
 * Emergency AI assessment: asks the basic profile, symptom assessment and
 * medical history questions, then generates an AI answer at the end.
 *
 * The answer is generated by the built-in offline AI engine, or by the real
 * Gemini API when the user has configured an API key (top-bar settings icon).
 */
@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun EmergencyAssessmentScreen(language: String, onBack: () -> Unit) {
    val context = LocalContext.current
    var step by rememberSaveable { mutableStateOf(0) }
    var answers by remember { mutableStateOf(AssessmentAnswers()) }
    var result by remember { mutableStateOf<AssessmentResult?>(null) }
    var generating by remember { mutableStateOf(false) }
    var notice by remember { mutableStateOf<String?>(null) }
    var showKeyDialog by remember { mutableStateOf(false) }
    val snackbarHostState = remember { SnackbarHostState() }

    // Voice assistant: answer the free-text questions by speaking.
    val speakOtherSymptoms = rememberSpeechRecognizer(
        language = language,
        onResult = { text ->
            answers = answers.copy(
                otherSymptoms = (answers.otherSymptoms.trim() + " " + text).trim()
            )
        },
        onError = { notice = it }
    )
    val speakMedicines = rememberSpeechRecognizer(
        language = language,
        onResult = { text ->
            answers = answers.copy(
                medicationsText = (answers.medicationsText.trim() + " " + text).trim()
            )
        },
        onError = { notice = it }
    )

    LaunchedEffect(notice) {
        val message = notice
        if (message != null) {
            snackbarHostState.showSnackbar(message)
            notice = null
        }
    }

    fun generateAssessment() {
        if (generating) return
        generating = true
        val apiKey = AiSettings.getApiKey(context)
        if (apiKey.isBlank()) {
            // Offline built-in AI engine - always works.
            result = HealthAssessmentEngine.generate(answers, language)
            generating = false
        } else {
            // Real AI (Gemini) when a key is configured; fall back offline on failure.
            GeminiAssessmentClient.generate(
                apiKey = apiKey,
                answers = answers,
                language = language,
                onResult = { generated ->
                    result = generated
                    generating = false
                },
                onError = { _ ->
                    result = HealthAssessmentEngine.generate(answers, language)
                    generating = false
                    notice = loc(
                        language,
                        "AI service unavailable - answered with the built-in AI instead.",
                        "Tajaajilin AI hin jiru - AI ofii nageenyaa haan fayyadamne.",
                        "የአይ አይ አገልጋይ አይገኝም — በተገኘው አይ አይ ተቀርጿል።"
                    )
                }
            )
        }
    }

    Scaffold(
        topBar = {
            TopAppBar(
                title = {
                    Text(
                        loc(
                            language,
                            "Emergency AI Assessment",
                            "Madaallii AI Ariifachisaa",
                            "የአስቸኳይ የአይ አይ ግምገማ"
                        )
                    )
                },
                navigationIcon = {
                    IconButton(onClick = onBack) {
                        Icon(Icons.AutoMirrored.Filled.ArrowBack, contentDescription = "Back")
                    }
                },
                actions = {
                    IconButton(onClick = { showKeyDialog = true }) {
                        Icon(Icons.Default.Settings, contentDescription = "AI settings")
                    }
                }
            )
        },
        snackbarHost = { SnackbarHost(snackbarHostState) }
    ) { padding ->
        Column(
            modifier = Modifier
                .padding(padding)
                .padding(16.dp)
                .fillMaxSize()
        ) {
            val currentResult = result
            if (currentResult != null) {
                ResultView(
                    result = currentResult,
                    language = language,
                    onRestart = {
                        step = 0
                        answers = AssessmentAnswers()
                        result = null
                    },
                    onDone = onBack
                )
            } else {
                LinearProgressIndicator(
                    progress = { (step + 1) / TOTAL_STEPS.toFloat() },
                    modifier = Modifier.fillMaxWidth()
                )
                Spacer(modifier = Modifier.height(12.dp))
                Text(
                    text = sectionTitle(step, language),
                    style = MaterialTheme.typography.labelMedium,
                    color = MaterialTheme.colorScheme.primary
                )
                Spacer(modifier = Modifier.height(4.dp))
                Text(
                    text = questionTitle(step, language),
                    style = MaterialTheme.typography.titleMedium,
                    fontWeight = FontWeight.Bold
                )
                Spacer(modifier = Modifier.height(12.dp))

                Column(
                    modifier = Modifier
                        .weight(1f)
                        .verticalScroll(rememberScrollState())
                ) {
                    when (step) {
                        0 -> AgeStep(answers, language) { answers = it }
                        1 -> SingleChoiceStep(
                            options = AssessmentOptions.genders,
                            selected = answers.gender,
                            language = language,
                            onSelect = { id -> answers = answers.copy(gender = id) }
                        )

                        2 -> SymptomsStep(
                            answers = answers,
                            language = language,
                            onChange = { answers = it },
                            onSpeak = { speakOtherSymptoms() }
                        )

                        3 -> SingleChoiceStep(
                            options = AssessmentOptions.durations,
                            selected = answers.duration,
                            language = language,
                            onSelect = { id -> answers = answers.copy(duration = id) }
                        )

                        4 -> SingleChoiceStep(
                            options = AssessmentOptions.severities,
                            selected = answers.severity,
                            language = language,
                            onSelect = { id -> answers = answers.copy(severity = id) }
                        )

                        5 -> ConditionsStep(
                            answers = answers,
                            language = language,
                            onChange = { answers = it }
                        )

                        6 -> MedicationsStep(
                            answers = answers,
                            language = language,
                            onChange = { answers = it },
                            onSpeak = { speakMedicines() }
                        )

                        7 -> YesNoStep(
                            questionIndex = step,
                            selected = answers.allergies,
                            language = language,
                            onSelect = { id -> answers = answers.copy(allergies = id) }
                        )

                        else -> YesNoStep(
                            questionIndex = step,
                            selected = answers.hadBefore,
                            language = language,
                            onSelect = { id -> answers = answers.copy(hadBefore = id) }
                        )
                    }
                }

                Spacer(modifier = Modifier.height(12.dp))

                if (generating) {
                    Row(
                        modifier = Modifier.fillMaxWidth(),
                        verticalAlignment = Alignment.CenterVertically,
                        horizontalArrangement = Arrangement.Center
                    ) {
                        CircularProgressIndicator(modifier = Modifier.size(24.dp))
                        Spacer(modifier = Modifier.width(12.dp))
                        Text(
                            loc(
                                language,
                                "AI is preparing your answer...",
                                "AI jawaabii keessan qopheessaa jira...",
                                "አይ አይ መልስዎን በማዘጋጀት ላይ ነው..."
                            )
                        )
                    }
                } else {
                    Row(
                        modifier = Modifier.fillMaxWidth(),
                        horizontalArrangement = Arrangement.spacedBy(8.dp)
                    ) {
                        OutlinedButton(
                            onClick = { if (step > 0) step-- },
                            enabled = step > 0,
                            modifier = Modifier.weight(1f)
                        ) {
                            Text(loc(language, "Back", "Deebi'i", "ተመለስ"))
                        }
                        Button(
                            onClick = {
                                if (step < TOTAL_STEPS - 1) step++ else generateAssessment()
                            },
                            enabled = isStepValid(step, answers),
                            modifier = Modifier.weight(1f)
                        ) {
                            Text(
                                if (step < TOTAL_STEPS - 1) {
                                    loc(language, "Next", "Itti aanu", "ቀጣይ")
                                } else {
                                    loc(
                                        language,
                                        "Generate AI answer",
                                        "Yakkaa AI barreessi",
                                        "የአይ አይ መልስ ይፍጠሩ"
                                    )
                                }
                            )
                        }
                    }
                }
            }
        }
    }

    if (showKeyDialog) {
        ApiKeyDialog(
            language = language,
            onDismiss = { showKeyDialog = false },
            onSaved = { key ->
                if (key.isBlank()) AiSettings.clearApiKey(context) else AiSettings.setApiKey(context, key)
                showKeyDialog = false
                notice = loc(
                    language,
                    "AI settings saved.",
                    "Qindaa'ina AI olkaa'ameera.",
                    "የአይ አይ ቅንብሮች ተቀምጠዋል።"
                )
            }
        )
    }
}

// ------------------------------------------------------------ step validity

private fun isStepValid(step: Int, a: AssessmentAnswers): Boolean = when (step) {
    0 -> a.age.toIntOrNull()?.let { it in 0..120 } == true
    1 -> a.gender != null
    2 -> a.symptoms.any { it != "other" } || a.otherSymptoms.isNotBlank()
    3 -> a.duration != null
    4 -> a.severity != null
    5 -> a.conditions.isNotEmpty()
    6 -> a.onMedications != null
    7 -> a.allergies != null
    else -> a.hadBefore != null
}

