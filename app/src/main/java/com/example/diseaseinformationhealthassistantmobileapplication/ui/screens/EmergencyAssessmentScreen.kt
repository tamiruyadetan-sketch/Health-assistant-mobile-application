// ------------------------------------------------------------- API key dialog

@Composable
private fun ApiKeyDialog(
    language: String,
    onDismiss: () -> Unit,
    onSaved: (String) -> Unit
) {
    val context = LocalContext.current
    var keyField by remember { mutableStateOf(AiSettings.getApiKey(context)) }
    val hasStoredKey = AiSettings.getApiKey(context).isNotBlank()

    AlertDialog(
        onDismissRequest = onDismiss,
        title = {
            Text(loc(language, "AI settings", "Qindaa'ina AI", "የአይ አይ ቅንብሮች"))
        },
        text = {
            Column {
                Text(
                    text = if (hasStoredKey) {
                        loc(
                            language,
                            "A Gemini API key is saved - answers are generated by the Gemini AI.",
                            "Furtuun Gemini API dhuunfamee jira - AI-n Gemini-tiin jawaabii barreessa.",
                            "የጂሚኒ አፒአይ ቁልፍ ተቀምጧል - መልሶች በጂሚኒ አይ አይ ይፈጠራሉ።"
                        )
                    } else {
                        loc(
                            language,
                            "No API key - answers are generated by the built-in offline AI.",
                            "Furtuu API hin jiru - AI ofii (of-laayinii) jawaabii barreessa.",
                            "የአፒአይ ቁልፍ የለም - መልሶች በመሣሪያው ውስጥ ያለው አይ አይ ይፈጠራሉ።"
                        )
                    },
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.secondary
                )
                Spacer(modifier = Modifier.height(12.dp))
                OutlinedTextField(
                    value = keyField,
                    onValueChange = { keyField = it },
                    label = { Text("Gemini API key") },
                    singleLine = true,
                    visualTransformation = PasswordVisualTransformation(),
                    keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Password),
                    modifier = Modifier.fillMaxWidth()
                )
                Spacer(modifier = Modifier.height(8.dp))
                Text(
                    text = loc(
                        language,
                        "Paste a Google AI Studio key. Save an empty key to use only the built-in AI.",
                        "Furtuu Google AI Studio dhangii. AI ofii qofa fayyadamuuf furtuu duwwaa olkaa'i.",
                        "የGoogle AI Studio ቁልፍ ይለጥፉ። በተገኘው አይ አይ ብቻ ለመጠቀም ባዶ ቁልፍ ያስቀምጡ።"
                    ),
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.secondary
                )
            }
        },
        confirmButton = {
            TextButton(onClick = { onSaved(keyField) }) {
                Text(loc(language, "Save", "Olkaa'i", "አስቀምጥ"))
            }
        },
        dismissButton = {
            TextButton(onClick = onDismiss) {
                Text(loc(language, "Cancel", "Dhaabi", "ሰርዝ"))
            }
        }
    )
}
