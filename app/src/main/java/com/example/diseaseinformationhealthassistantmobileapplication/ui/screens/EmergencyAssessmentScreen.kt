                "If yes, tell the health worker about it.",
                "Yoo eeyyee, hojii fayyaatti dhabbisi.",
                "አዎ ከሆነ ለጤና አገልጋይ ይንገሩ።"
            )
            else -> loc(
                language,
                "This helps the AI give a better answer.",
                "Kun AI-n jawaabii caalaa kennuuf gargaara.",
                "ይህ አይ አይ የተሻለ መልስ ለማፍሰስ ይረዳል።"
            )
        },
        style = MaterialTheme.typography.bodySmall,
        color = MaterialTheme.colorScheme.secondary
    )
}

// ------------------------------------------------------------- result view

@Composable
private fun ResultView(
    result: AssessmentResult,
    language: String,
    onRestart: () -> Unit,
    onDone: () -> Unit
) {
    val context = LocalContext.current
    val containerColor = when (result.urgency) {
        Urgency.EMERGENCY -> MaterialTheme.colorScheme.errorContainer
        Urgency.URGENT -> MaterialTheme.colorScheme.tertiaryContainer
        Urgency.SELF_CARE -> MaterialTheme.colorScheme.secondaryContainer
    }
    val contentColor = when (result.urgency) {
        Urgency.EMERGENCY -> MaterialTheme.colorScheme.onErrorContainer
        Urgency.URGENT -> MaterialTheme.colorScheme.onTertiaryContainer
        Urgency.SELF_CARE -> MaterialTheme.colorScheme.onSecondaryContainer
    }
    val headline = when (result.urgency) {
        Urgency.EMERGENCY -> loc(
            language,
            "EMERGENCY - Get help now",
            "ARIIFACHISAA - Gargaarsa amma barbaadi",
            "አስቸኳይ - አሁን እርዳታ ይጠይቁ"
        )

        Urgency.URGENT -> loc(
            language,
            "URGENT - See a health professional today",
            "LOOSA - Amma gara hojii fayyaa deemii",
            "አስቸኳይ የሚሰጠው - ዛሬ የሕክምና ባለሙያ ይጠይቁ"
        )

